TEST_CASE(zlib_fixed_codes)
{
    auto output = MUST(zlib_decompress({ zlib_fixed, sizeof(zlib_fixed) }));
    EXPECT_EQ(output.size(), zlib_fixed_text.length());
    EXPECT(__builtin_memcmp(output.data(), zlib_fixed_text.characters_without_null_termination(), output.size()) == 0);
}

TEST_CASE(zlib_dynamic_codes)
{
    auto output = MUST(zlib_decompress({ zlib_dynamic, sizeof(zlib_dynamic) }));
    EXPECT_EQ(output.size(), zlib_dynamic_size);
    EXPECT_EQ(adler32(output.span()), zlib_dynamic_adler);
}

TEST_CASE(stored_blocks)
{
    // Two stored blocks, the first not final.
    constexpr u8 data[] = { 0x00, 0x03, 0x00, 0xfc, 0xff, 'a', 'b', 'c', 0x01, 0x02, 0x00, 0xfd, 0xff, 'd', 'e' };
    auto output = MUST(inflate({ data, sizeof(data) }));
    EXPECT_EQ(output.size(), 5u);
    EXPECT(__builtin_memcmp(output.data(), "abcde", 5) == 0);
}

TEST_CASE(round_trips)
{
    auto check = [](Vector<u8> const& input) {
        auto compressed = MUST(zlib_compress(input.span()));
        auto back = MUST(zlib_decompress(compressed.span()));
        EXPECT_EQ(back.size(), input.size());
        EXPECT(input.is_empty() || __builtin_memcmp(back.data(), input.data(), input.size()) == 0);
        return compressed.size();
    };
    EXPECT(check({}) < 16);
    Vector<u8> repetitive;
    for (int i = 0; i < 100000; ++i)
        repetitive.append(static_cast<u8>(i % 7));
    EXPECT(check(repetitive) < 2000);
    Vector<u8> noisy;
    u32 state = 1;
    for (int i = 0; i < 70000; ++i) {
        state = state * 1103515245 + 12345;
        noisy.append(static_cast<u8>(state >> 16));
    }
    check(noisy);
    // Matches at the longest distance and length.
    Vector<u8> distant;
    for (int i = 0; i < 40000; ++i)
        distant.append(static_cast<u8>((i * 31) >> 3));
    for (int i = 0; i < 40000; ++i)
        distant.append(distant[static_cast<size_t>(i)]);
    check(distant);
    EXPECT_EQ(adler32({ reinterpret_cast<u8 const*>("Wikipedia"), 9 }), 0x11e60398u);
}

TEST_CASE(bad_input_fails_cleanly)
{
    constexpr u8 reserved_block[] = { 0x07 };
    EXPECT(inflate({ reserved_block, 1 }).is_error());
    constexpr u8 bad_stored[] = { 0x01, 0x03, 0x00, 0x00, 0x00, 'a', 'b', 'c' };
    EXPECT(inflate({ bad_stored, sizeof(bad_stored) }).is_error());
    EXPECT(inflate({ zlib_fixed + 2, 4 }).is_error());
    EXPECT(zlib_decompress({ zlib_fixed, 4 }).is_error());
    u8 flipped[sizeof(zlib_fixed)];
    __builtin_memcpy(flipped, zlib_fixed, sizeof(zlib_fixed));
    flipped[sizeof(flipped) - 1] ^= 1;
    EXPECT(zlib_decompress({ flipped, sizeof(flipped) }).is_error());
    EXPECT(zlib_decompress({ zlib_fixed, sizeof(zlib_fixed) }, 10).is_error());
    // Every corruption of a stream fails or gives something: never a crash.
    for (size_t i = 0; i < sizeof(zlib_dynamic); ++i) {
        u8 copy[sizeof(zlib_dynamic)];
        __builtin_memcpy(copy, zlib_dynamic, sizeof(copy));
        copy[i] ^= 0x55;
        (void)inflate({ copy + 2, sizeof(copy) - 2 }, 100000);
    }
}
